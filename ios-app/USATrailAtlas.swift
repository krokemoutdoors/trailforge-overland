import CoreLocation
import Foundation

enum USATrailAtlas {
    static let all: [OverlandTrail] = specs.map(make)

    static var states: [String] {
        Array(Set(all.map(\.state))).sorted()
    }

    private static func make(_ spec: AtlasSpec) -> OverlandTrail {
        let seed = TrailGeometry.seed(for: spec.id)
        let coordinates = handRoutes[spec.id] ?? bdrCoordinates[spec.id] ?? TrailGeometry.route(
            lat: spec.lat,
            lon: spec.lon,
            seed: seed,
            kilometers: spec.km
        )
        let camps = handCamps[spec.id] ?? bdrCamps[spec.id] ?? TrailGeometry.pads(lat: spec.lat, lon: spec.lon, seed: seed)
        return OverlandTrail(
            id: spec.id,
            name: spec.name,
            region: spec.region,
            agency: spec.agency,
            distanceMi: spec.miles,
            peakElevFt: spec.elev,
            reqClearanceIn: spec.clearance,
            minCanopyFt: spec.canopy,
            waterCrossingIn: spec.water,
            reqLocker: spec.locker,
            gateStatus: spec.gate,
            snotelSnowIn: spec.snow,
            usgsFlowCfs: spec.flow,
            state: spec.state,
            centerLat: spec.lat,
            centerLon: spec.lon,
            coordinates: coordinates,
            flatCamps: camps,
            isBDR: spec.bdr,
            alsoStates: spec.alsoStates
        )
    }
}

